def mk_after(anchor_p, kind, **kw):
    p = doc.add_paragraph()
    if kind == "img":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf = p.paragraph_format
        pf.space_before, pf.space_after, pf.line_spacing = Pt(6), Pt(2), 1.0
        p.add_run().add_picture(kw["path"], width=Cm(kw["width"]))
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf = p.paragraph_format
        pf.space_before, pf.space_after, pf.line_spacing = Pt(0), Pt(6 if kind == "note" else 3), 1.0
