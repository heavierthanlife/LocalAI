def norm(s):
    return re.sub(r"\s+", "", s)


def replace_para(anchor, new_text, count=1):
    """把第一个包含 anchor 的正文段落整体替换。"""
    hit = 0
    for it in items:
        if it.get("t") == "p" and anchor in it.get("text", ""):
            it["text"] = new_text
            hit += 1
            if hit >= count:
                return hit
    print("[WARN] 未命中:", anchor[:30])
    return hit


def replace_any(anchor, new_text, kinds=("p",)):
    hit = 0
    for it in items:
        if it.get("t") in kinds and anchor in (it.get("text") or ""):
            it["text"] = new_text
            hit += 1
    if not hit:
        print("[WARN] 未命中:", anchor[:30])
    return hit


def fix_numbering(s):
    s = re.sub(r"图\s*(\d+)-(\d+)", r"图\1.\2", s)
    s = re.sub(r"表\s*(\d+)-(\d+)", r"表\1.\2", s)
    return s


