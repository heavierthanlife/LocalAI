# ---------------- 工具
def para(text, style="正文1"):
    p = anchor.insert_paragraph_before(text, style=style)
    return p

def set_fonts(r, cjk=SONG, latin=TNR, size=10.5, bold=False):
    r.font.name = latin; r.font.size = Pt(size); r.bold = bold
    rPr = r._element.get_or_add_rPr()
    rf = rPr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts"); rPr.append(rf)
    rf.set(qn("w:ascii"), latin); rf.set(qn("w:hAnsi"), latin); rf.set(qn("w:eastAsia"), cjk)

def table(rows, ratios, note="", en_cap="", cap=""):
    if cap:
        para(cap, "表题")
    if en_cap:
        para(en_cap, "图题EN")
    nrow, ncol = len(rows), len(rows[0])
    t = d.add_table(rows=nrow, cols=ncol)
    anchor._p.addprevious(t._tbl)
    total = 15.0
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.width = Cm(total * ratios[ci])
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 0 else WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.first_line_indent = Pt(0)
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.line_spacing = 1.0
            r = p.add_run(str(val))
            set_fonts(r, bold=(ri == 0))
            # 三线
            tcPr = cell._tc.get_or_add_tcPr()
            for old in tcPr.findall(qn("w:tcBorders")):
                tcPr.remove(old)
            cb = OxmlElement("w:tcBorders")
            for edge in ("top", "bottom"):
                use = (edge == "top" and ri == 0) or (edge == "bottom" and (ri == 0 or ri == nrow - 1))
                if use:
                    e = OxmlElement(f"w:{edge}")
                    e.set(qn("w:val"), "single"); e.set(qn("w:sz"), "4"); e.set(qn("w:color"), "000000")
                    cb.append(e)
            if len(cb):
                tcPr.append(cb)
    # 表头重复 + 行高
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader"); th.set(qn("w:val"), "true"); trPr.append(th)
    for row in t.rows:
        trPr = row._tr.get_or_add_trPr()
        trh = OxmlElement("w:trHeight"); trh.set(qn("w:val"), "448"); trh.set(qn("w:hRule"), "atLeast")
        trPr.insert(0, trh)
    if note:
        para(note, "图注")

