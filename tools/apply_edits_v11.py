def apply(path, edits):
    s = io.open(path, encoding='utf-8').read()
    for old, new in edits:
        n = s.count(old)
        if n != 1:
            print(f"!! {path}: pattern count={n} for: {old[:40]}...")
            sys.exit(1)
        s = s.replace(old, new)
    io.open(path, 'w', encoding='utf-8').write(s)
    print(f"OK {path}: {len(edits)} edits")

