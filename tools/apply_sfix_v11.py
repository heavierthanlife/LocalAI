# -*- coding: utf-8 -*-
import io, sys

def edit(path, pairs):
    s = io.open(path, encoding='utf-8').read()
    for old,new in pairs:
        n=s.count(old)
        if n!=1:
            print(f"!! {path} count={n}: {old[:45]}"); sys.exit(1)
        s=s.replace(old,new)
    io.open(path,'w',encoding='utf-8').write(s)
    print(f"OK {path}: {len(pairs)}")

